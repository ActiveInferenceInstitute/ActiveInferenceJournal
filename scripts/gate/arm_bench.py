"""Arm: bench - measure every arm and refresh the timings document.

The table in docs/_generated/gate-timings.md is produced here; no timing in the
documentation is typed by hand. ``before`` values come from the recorded
pre-change baseline receipt, ``after`` values are measured on this host now.
"""

from __future__ import annotations

import json
import platform
import re
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

from cli import ARMS
from common import ROOT, log

MEASURED = ["lint", "docs", "identity", "fast", "full", "gnn"]
GENERATED = ROOT / "docs" / "_generated"
DOC = GENERATED / "gate-timings.md"
BASELINE = GENERATED / "gate-baseline.json"


def measure(arm: str, extra: list[str]) -> float:
    started = time.perf_counter()
    completed = subprocess.run(
        [str(ROOT / "run.sh"), arm, *extra],
        cwd=str(ROOT),
        stdout=None if arm == "lint" else subprocess.DEVNULL,
    )
    seconds = time.perf_counter() - started
    if completed.returncode != 0:
        raise SystemExit(f"bench: arm `{arm}` failed (exit {completed.returncode})")
    log(f"bench: {arm} -> {seconds:.2f}s")
    return seconds


def load_baseline() -> dict:
    if not BASELINE.exists():
        return {}
    return json.loads(BASELINE.read_text(encoding="utf-8"))


def render(measured: dict[str, float], baseline: dict) -> str:
    recorded = baseline.get("recorded", "n/a")
    host = baseline.get("host", "n/a")
    lines = [
        "# Gate timings",
        "",
        "<!-- generated by scripts/gate/arm_bench.py (`./run.sh bench`); do not edit -->",
        "",
        "Wall time per gate arm, one run each, on the host named at the bottom.",
        f"The `before` column is the recorded pre-change baseline ({recorded}, {host});",
        "`after` is the current checkout measured by `./run.sh bench`. Arms that did not",
        "exist before the gate was introduced have no `before` value.",
        "",
        "| before (s) | after (s) | arm |",
        "| --- | --- | --- |",
    ]
    for arm in MEASURED:
        after = f"{measured[arm]:.2f}s" if arm in measured else "pending"
        before = baseline.get("arms", {}).get(arm)
        before_cell = f"{before:.2f}s" if before is not None else "new arm"
        lines.append(f"| {before_cell} | {after} | `{arm}` |")

    lines += [
        "",
        "`gnn` is measured **cold**: `./run.sh bench --cold` discards the cached parser",
        "environment first, because a warm cache hides the install that dominated the old",
        "inline CI step (pip's own wheel cache is *not* cleared, so a first-ever network",
        "install is slower than the number here). `fast` is a subset of `full`, and `all`",
        "runs `lint`, `docs`, `full` and `gnn`, so nothing is checked twice.",
        "",
        "`full` is dominated by `validate_journal.py`, which varies by tens of percent",
        "between runs on the same host; treat a single-run difference of that size as",
        "noise, not as a regression. `gnn` is the only arm whose cost is network-bound.",
        "",
        "## What each arm runs",
        "",
        "| arm | command |",
        "| --- | --- |",
    ]
    commands = baseline.get("commands", {})
    for arm in MEASURED:
        command = commands.get(arm) or f"`./run.sh {arm}` - {ARMS[arm]}"
        lines.append(f"| `{arm}` | {command} |")

    lines += [
        "",
        "## Setup that is not an arm",
        "",
        "| step | cold (s) |",
        "| --- | --- |",
    ]
    for step, seconds in baseline.get("setup", {}).items():
        lines.append(f"| {step} | {seconds:.2f}s |")
    lines += [
        "",
        "Journal-Utilities is materialized once from the pin into the gate cache and",
        "reused by `fast` and `full`; in CI the checkout step already provides it, so",
        "that row is a local-only cost, paid inside the first local `fast`/`full` run and",
        "reused afterwards; CI does not pay it. The remaining rows are paid by `gnn`.",
        "",
        f"Measured {datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')} with "
        f"Python {platform.python_version()} on {platform.system()} {platform.machine()}.",
        "",
    ]
    return "\n".join(lines)


def run(argv: list[str]) -> int:
    cold = "--cold" in argv
    unknown = [item for item in argv if item not in {"--cold", "--write", "--check"}]
    if unknown:
        raise SystemExit(f"bench: unknown arguments {unknown}")

    if "--check" in argv:
        if not DOC.exists():
            log("bench: docs/_generated/gate-timings.md is missing")
            return 1
        reported = set(re.findall(r"^\| [^|]+ \| [^|]+ \| `([a-z]+)` \|$", DOC.read_text(encoding="utf-8"), re.M))
        return 0 if reported == set(MEASURED) else 1

    baseline = load_baseline()
    GENERATED.mkdir(parents=True, exist_ok=True)
    # The docs arm validates this table. Render the current arm list first, with
    # every "after" pending, so measuring `docs` cannot fail against a table that
    # still describes the previous arms — an added arm would otherwise be unable
    # to produce the document that admits it.
    DOC.write_text(render({}, baseline), encoding="utf-8")

    measured: dict[str, float] = {}
    for arm in MEASURED:
        measured[arm] = measure(arm, ["--cold"] if (arm == "gnn" and cold) else [])

    DOC.write_text(render(measured, baseline), encoding="utf-8")
    log(f"bench: wrote {DOC.relative_to(ROOT)}")
    for arm in MEASURED:
        print(f"  {arm:<6} {measured[arm]:.2f}s", file=sys.stderr)
    return 0
